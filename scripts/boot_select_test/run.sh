#!/usr/bin/env bash
# An MCU-only reset selects the saved slot once, never slot 1 first
# (plans/AUDIT-2026-10-31.md, F-024; first written as the audit's verify-002).
# The real quantum/dip_switch.c, bt_ui.c and bluetooth/ch582f_ajazz.c, with
# dip_switch_update_kb() copied verbatim out of ak820pro.c by awk (the whole
# board otherwise), replaying keyboard.c's boot order: dip_switch_init()'s
# forced reading before the EEPROM, then post-init. A live module linked on
# slot 2 (an MCU-only reset: the watchdog, a deep sleep's reset, a return from
# the bootloader) must receive slot 2's select only, with no link drop (before
# the fix: A6 31, A6 31, A6 32 at 0, 2 and 4 ms); a cold boot
# with the module up 0 or 400 ms after the first pass, the saved slot.
# CC picks the compiler (default cc); SAN the sanitizer flags.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
fw="$here/../../qmk_firmware-ak820pro"
kb="$fw/keyboards/a_jazz/ak820pro"
cc="${CC:-cc}"
san="${SAN--fsanitize=address,undefined -fno-sanitize-recover=undefined}"
o="$(mktemp -d)"
trap 'rm -rf "$o"' EXIT
{ echo "/* GENERATED by run.sh from ak820pro.c (function copied verbatim). */"
  echo '#include "quantum.h"'; echo '#include "graphics/display.h"'; echo '#include "bt_ui.h"'
  echo 'bool dip_switch_update_user(uint8_t index, bool active);'; echo 'void prof_switch(bool mac);'
  awk '/^ *bool dip_switch_update_kb\(uint8_t index, bool active\) \{/{p=1} p{print} p && /^ \}$/{exit}' "$kb/ak820pro.c"
} > "$o/gen_dip_update_kb.c"
grep -q 'bt_ui_mode_slider(index, active)' "$o/gen_dip_update_kb.c"
# shellcheck disable=SC2086
"$cc" -g -O1 -std=gnu11 $san -Wall -Wno-unused-function -Wno-unused-variable -Wno-unused-but-set-variable \
    -I"$here/stubs" -I"$kb" -I"$kb/bluetooth" -DDIP_SWITCH_PINS='{ B1, B12, B13 }' \
    "$here/t_boot_reset.c" "$o/gen_dip_update_kb.c" "$fw/quantum/dip_switch.c" "$kb/bt_ui.c" "$kb/bluetooth/ch582f_ajazz.c" -o "$o/t"
fails=0
for m in live live-ignore "cold 0" "cold 400"; do
    # shellcheck disable=SC2086
    out="$("$o/t" $m)" || fails=1
    echo "$out" | head -2
    case "$m" in
        live*) # every select slot 2's (the driver's own retry repeats it at 1.5 s: a module on that slot
               # doesn't answer its select), no link dropped
               echo "$out" | grep -Eq "module received( A6 32@[0-9]+ms)+  \(link drops: 0, module ends on slot 2\)" ||
                   { echo "  FAIL: a select other than slot 2's, or the link dropped"; fails=1; } ;;
        *) echo "$out" | grep -q "module received.* A6 32@" || { echo "  FAIL: the saved slot never reached the module"; fails=1; } ;;
    esac
done
[[ $fails -eq 0 ]] && echo "RESULT: PASS" || { echo "RESULT: FAIL"; exit 1; }
