"""The indicator LEDs' duty table (plans/CONFIG-MENU-P1-DESIGN.md, "P2a"):
levels 0-100, 0 off, 1 one tick in 48 (the old level 1, the dimmest without
flicker), 100 full on, each step x 48^(1/99) (~1.04, even to the eye).
Writes qmk_firmware-ak820pro/keyboards/a_jazz/ak820pro/indicator_levels.h.

    venv-win/Scripts/python.exe scripts/gen_indicator_levels.py [--check] < /dev/null"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "qmk_firmware-ak820pro", "keyboards", "a_jazz", "ak820pro", "indicator_levels.h")
TICKS, SUB = 48, 256
FULL = TICKS * SUB


def table():
    t = [0] + [round(SUB * TICKS ** ((p - 1) / 99)) for p in range(1, 101)]
    if t[1] != SUB or t[100] != FULL:
        sys.exit(f"the ends: {t[1]}, {t[100]}")
    if any(b <= a for a, b in zip(t, t[1:])):
        sys.exit("not strictly increasing")
    return t


def render(t):
    rows = []
    for i in range(0, 101, 10):
        rows.append("    " + ", ".join(f"{v:5d}" for v in t[i:i + 10]) + ",")
    return f"""// Copyright 2026 JD Lien
// SPDX-License-Identifier: GPL-2.0-or-later
//
// GENERATED by scripts/gen_indicator_levels.py -- do not edit.
//
// The indicator LEDs' levels (plans/CONFIG-MENU-P1-DESIGN.md, "P2a"): 0 off,
// 1 one tick of {TICKS} (the old level 1, the dimmest without flicker), 100 full
// on, each step x {TICKS}^(1/99). Duties in 1/{SUB} tick. Pure: the host tests
// include it.
#pragma once

#include <stdbool.h>
#include <stdint.h>

#define IND_PWM_TICKS {TICKS}
#define IND_FULL      {FULL}u   /* IND_PWM_TICKS x {SUB}: always on */
#define IND_LEVEL_MAX 100u

static const uint16_t ind_level_duty[IND_LEVEL_MAX + 1] = {{
{chr(10).join(rows)}
}};

/* One tick of a group (first-order sigma-delta): on when the accumulator
 * passes IND_FULL. *acc stays below IND_FULL and *acc + duty below 2 x
 * IND_FULL, so a uint16_t holds both. Duty 0 never lights; IND_FULL always
 * does. */
static inline bool ind_sd_step(uint16_t *acc, uint16_t duty) {{
    uint16_t a  = (uint16_t)(*acc + duty);
    bool     on = a >= IND_FULL;
    if (on) a = (uint16_t)(a - IND_FULL);
    *acc = a;
    return on;
}}

/* One tick's output, bit 0 Caps, 1 Win lock, 2 charging: Caps and Win lock
 * share the locks' group, stepped while either is lit or the group is forced
 * (force bit 0); the charging group by itself (bit 1). An unlit group keeps
 * its accumulator, and its bits are clear. */
static inline uint8_t ind_tick_out(bool caps, bool win, bool chg, uint8_t force, uint16_t *acc_locks,
                                   uint16_t *acc_chg, uint16_t duty_locks, uint16_t duty_chg) {{
    const bool lc = caps || (force & 1u), lw = win || (force & 1u);
    uint8_t    out = 0;
    if ((lc || lw) && ind_sd_step(acc_locks, duty_locks)) out = (uint8_t)((lc ? 1u : 0u) | (lw ? 2u : 0u));
    if ((chg || (force & 2u)) && ind_sd_step(acc_chg, duty_chg)) out |= 4u;
    return out;
}}

/* The pins to write for `out` after `last`: those whose bit changed, or all
 * three when `last` is IND_OUT_UNKNOWN (the restart's, after the stop drove
 * every pin low: a pin meant to be on would otherwise be skipped and stay
 * dark; codex, P2a's design). */
#define IND_OUT_UNKNOWN 0xFFu
static inline uint8_t ind_pins_to_write(uint8_t out, uint8_t last) {{
    return last == IND_OUT_UNKNOWN ? 7u : (uint8_t)((out ^ last) & 7u);
}}
"""


def main():
    text = render(table())
    if "--check" in sys.argv:
        if open(OUT, encoding="utf-8").read() != text:
            sys.exit(f"{OUT} is stale: run scripts/gen_indicator_levels.py")
        print("indicator_levels.h is current")
        return
    open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
